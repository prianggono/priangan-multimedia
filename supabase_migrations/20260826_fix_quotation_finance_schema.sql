alter table public.penawaran_items add column if not exists durasi numeric default 1;
alter table public.penawaran_items add column if not exists subtotal numeric default 0;

update public.penawaran_items
set nama_item = coalesce(nullif(nama_item, ''), item, ''),
    harga = coalesce(harga, harga_jual, 0),
    tipe = coalesce(nullif(tipe, ''), tipe_perhitungan, 'qty'),
    jumlah = coalesce(jumlah, qty, 1),
    qty = coalesce(qty, jumlah, 1),
    harga_modal = coalesce(harga_modal, 0);

create index if not exists idx_penawaran_items_penawaran on public.penawaran_items(penawaran_id);

