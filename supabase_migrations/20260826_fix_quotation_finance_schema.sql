create table if not exists public.master_harga (
  id bigint generated by default as identity primary key,
  kode text,
  item text,
  kategori text default '',
  satuan text default '',
  harga_modal numeric not null default 0,
  harga_jual numeric not null default 0,
  aktif boolean not null default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.master_harga add column if not exists kode text;
alter table public.master_harga add column if not exists item text;
alter table public.master_harga add column if not exists kategori text default '';
alter table public.master_harga add column if not exists satuan text default '';
alter table public.master_harga add column if not exists harga_modal numeric default 0;
alter table public.master_harga add column if not exists harga_jual numeric default 0;
alter table public.master_harga add column if not exists aktif boolean default true;
alter table public.master_harga add column if not exists created_at timestamptz default now();
alter table public.master_harga add column if not exists updated_at timestamptz default now();

update public.master_harga
set harga_modal = coalesce(harga_modal, 0),
    harga_jual = coalesce(harga_jual, 0),
    aktif = coalesce(aktif, true);

create index if not exists idx_master_harga_kode on public.master_harga(kode);

