alter table public.penawaran_items add column if not exists harga numeric default 0;
alter table public.penawaran_items add column if not exists harga_modal numeric default 0;
alter table public.penawaran_items add column if not exists tipe_perhitungan text default 'qty';
alter table public.penawaran_items add column if not exists tipe text default 'qty';
alter table public.penawaran_items add column if not exists qty numeric default 1;
alter table public.penawaran_items add column if not exists jumlah numeric default 1;
