update public.penawaran
set nama_event = coalesce(nullif(nama_event, ''), event_name, ''),
    event = coalesce(nullif(event, ''), event_name, ''),
    project = coalesce(nullif(project, ''), event_name, ''),
    grand_total = coalesce(grand_total, total, 0),
    tanggal_penawaran = coalesce(tanggal_penawaran, tanggal, created_at::date),
    tanggal = coalesce(tanggal, tanggal_penawaran, created_at::date),
    diskon = coalesce(diskon, 0),
    discount = coalesce(discount, diskon, 0),
    nilai_diskon = coalesce(nilai_diskon, diskon, 0),
    persen_diskon = coalesce(persen_diskon, 0),
    discount_percent = coalesce(discount_percent, persen_diskon, 0);

create index if not exists idx_penawaran_status on public.penawaran(status);
create index if not exists idx_penawaran_created_at on public.penawaran(created_at desc);

create table if not exists public.penawaran_items (
  id bigint generated by default as identity primary key,
  penawaran_id bigint references public.penawaran(id) on delete cascade,
  kode text default '',
  item text default '',
  harga_jual numeric default 0,
  tipe_perhitungan text default 'qty',
  qty numeric default 1,
  lebar numeric,
  tinggi numeric,
  panjang numeric,
  subtotal numeric default 0,
  created_at timestamptz default now()
);

